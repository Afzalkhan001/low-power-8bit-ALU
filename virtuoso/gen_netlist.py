"""
Generate the transistor-level Spectre netlists for the low-power 8-bit ALU.

    python virtuoso/gen_netlist.py                 # gpdk045 defaults
    python virtuoso/gen_netlist.py --pdk gpdk090
    python virtuoso/gen_netlist.py --pdk gpdk180 --model-file /cad/gpdk180/models/spectre/gpdk.scs

Writes (in this folder):
  cells.scs          CMOS standard cells (INV, BUF, NAND2, NOR2, AND2, OR2, XOR2, XNOR2,
                     TG MUX2, TG MUX4, 28T mirror full adder)
  alu8.scs           the 8-bit ALU (one subckt, 5 separate supply pins for per-unit power)
  tb_alu8.scs        transient testbench, operand isolation ON
  tb_alu8_noiso.scs  same stimulus, operand isolation OFF (for the low-power comparison)
  alu8_check.ocn     OCEAN script: checks every vector vs the golden model, prints power/delay

The gate structure comes from model/alu_gates.py (same source as the web simulator).
"""
import argparse, csv, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "model"))
from alu_gates import build, CELL_PINS, INPUTS, OUTPUTS, GND, VDD  # noqa: E402

# Model names / sizes per Cadence Generic PDK. Check them against your PDK install:
# place one nmos in a schematic, netlist it in ADE, and copy the model name you see.
PDKS = {
    "gpdk045": dict(nmos="g45n1svt", pmos="g45p1svt", l="45n", wn="120n", wp="240n", vdd=1.0,
                    model_file="/path/to/gpdk045/models/spectre/gpdk045.scs", section="tt"),
    "gpdk090": dict(nmos="gpdk090_nmos1v", pmos="gpdk090_pmos1v", l="100n", wn="120n", wp="240n",
                    vdd=1.2, model_file="/path/to/gpdk090/models/spectre/gpdk090.scs", section="NN"),
    "gpdk180": dict(nmos="nmos1", pmos="pmos1", l="180n", wn="400n", wp="800n", vdd=1.8,
                    model_file="/path/to/gpdk180/models/spectre/gpdk.scs", section="stat"),
}

UNIT_SUPPLY = {"ctrl": "vdd_ctrl", "arith": "vdd_arith", "mul": "vdd_mul",
               "logic": "vdd_logic", "shift": "vdd_shift"}
CELL_NAME = {t: t.lower() for t in CELL_PINS}
T_PERIOD_NS = 10.0
T_RISE_PS = 50


def cells_text(p):
    N, P, L, WN, WP = p["nmos"], p["pmos"], p["l"], p["wn"], p["wp"]

    def n(name, d, g, s):  return f"    {name} ({d} {g} {s} vss) {N} w={WN} l={L}"
    def pm(name, d, g, s): return f"    {name} ({d} {g} {s} vdd) {P} w={WP} l={L}"

    out = ["// CMOS cells for the low-power 8-bit ALU  (generated by gen_netlist.py)",
           f"// PDK preset: nmos={N} pmos={P}  L={L}  Wn={WN}  Wp={WP} (minimum size = low power)",
           "simulator lang=spectre", ""]

    def sub(name, pins, body, note):
        out.append(f"// {note}")
        out.append(f"subckt {name} ({' '.join(pins)} vdd vss)")
        out.extend(body)
        out.append(f"ends {name}\n")

    sub("inv", ["a", "y"], [pm("MP", "y", "a", "vdd"), n("MN", "y", "a", "vss")], "inverter, 2T")
    sub("buf", ["a", "y"], [pm("MP1", "x", "a", "vdd"), n("MN1", "x", "a", "vss"),
                            pm("MP2", "y", "x", "vdd"), n("MN2", "y", "x", "vss")], "buffer, 4T")
    sub("nand2", ["a", "b", "y"], [pm("MP1", "y", "a", "vdd"), pm("MP2", "y", "b", "vdd"),
                                   n("MN1", "y", "a", "x"), n("MN2", "x", "b", "vss")], "NAND2, 4T")
    sub("nor2", ["a", "b", "y"], [pm("MP1", "x", "a", "vdd"), pm("MP2", "y", "b", "x"),
                                  n("MN1", "y", "a", "vss"), n("MN2", "y", "b", "vss")], "NOR2, 4T")
    sub("and2", ["a", "b", "y"], [pm("MP1", "x", "a", "vdd"), pm("MP2", "x", "b", "vdd"),
                                  n("MN1", "x", "a", "x1"), n("MN2", "x1", "b", "vss"),
                                  pm("MP3", "y", "x", "vdd"), n("MN3", "y", "x", "vss")],
        "AND2 = NAND2 + INV, 6T (also used as operand-isolation gate)")
    sub("or2", ["a", "b", "y"], [pm("MP1", "x1", "a", "vdd"), pm("MP2", "x", "b", "x1"),
                                 n("MN1", "x", "a", "vss"), n("MN2", "x", "b", "vss"),
                                 pm("MP3", "y", "x", "vdd"), n("MN3", "y", "x", "vss")],
        "OR2 = NOR2 + INV, 6T")
    sub("xor2", ["a", "b", "y"], [
        pm("MPA", "an", "a", "vdd"), n("MNA", "an", "a", "vss"),
        pm("MPB", "bn", "b", "vdd"), n("MNB", "bn", "b", "vss"),
        n("MN1", "y", "a", "x1"), n("MN2", "x1", "b", "vss"),
        n("MN3", "y", "an", "x2"), n("MN4", "x2", "bn", "vss"),
        pm("MP1", "x3", "a", "vdd"), pm("MP2", "x3", "b", "vdd"),
        pm("MP3", "y", "an", "x3"), pm("MP4", "y", "bn", "x3")], "static CMOS XOR2, 12T")
    sub("xnor2", ["a", "b", "y"], [
        pm("MPA", "an", "a", "vdd"), n("MNA", "an", "a", "vss"),
        pm("MPB", "bn", "b", "vdd"), n("MNB", "bn", "b", "vss"),
        n("MN1", "y", "a", "x1"), n("MN2", "x1", "bn", "vss"),
        n("MN3", "y", "an", "x2"), n("MN4", "x2", "b", "vss"),
        pm("MP1", "x3", "a", "vdd"), pm("MP2", "x3", "bn", "vdd"),
        pm("MP3", "y", "an", "x3"), pm("MP4", "y", "b", "x3")], "static CMOS XNOR2, 12T")
    sub("mux2", ["sel", "d0", "d1", "y"], [
        pm("MPI", "seln", "sel", "vdd"), n("MNI", "seln", "sel", "vss"),
        n("MN0", "y", "seln", "d0"), pm("MP0", "y", "sel", "d0"),
        n("MN1", "y", "sel", "d1"), pm("MP1", "y", "seln", "d1")],
        "transmission-gate 2:1 mux, 6T  (sel=0 -> d0, sel=1 -> d1)")
    sub("mux4", ["s1", "s0", "d0", "d1", "d2", "d3", "y"], [
        "    I0 (s0 d0 d1 m0 vdd vss) mux2",
        "    I1 (s0 d2 d3 m1 vdd vss) mux2",
        "    I2 (s1 m0 m1 m2 vdd vss) mux2",
        pm("MPB1", "m3", "m2", "vdd"), n("MNB1", "m3", "m2", "vss"),
        pm("MPB2", "y", "m3", "vdd"), n("MNB2", "y", "m3", "vss")],
        "transmission-gate 4:1 mux + restoring buffer, 22T  (y = d[2*s1+s0])")
    sub("fa", ["a", "b", "ci", "s", "co"], [
        "    // carry (mirror):  cn = ~(a.b + ci.(a+b))",
        n("MN1", "x1", "a", "vss"), n("MN2", "x1", "b", "vss"), n("MN3", "cn", "ci", "x1"),
        n("MN4", "cn", "a", "x2"), n("MN5", "x2", "b", "vss"),
        pm("MP1", "x3", "a", "vdd"), pm("MP2", "x3", "b", "vdd"), pm("MP3", "cn", "ci", "x3"),
        pm("MP4", "cn", "a", "x4"), pm("MP5", "x4", "b", "vdd"),
        "    // sum (mirror):  sn = ~(a.b.ci + cn.(a+b+ci))",
        n("MN6", "x5", "a", "vss"), n("MN7", "x5", "b", "vss"), n("MN8", "x5", "ci", "vss"),
        n("MN9", "sn", "cn", "x5"),
        n("MN10", "sn", "a", "x6"), n("MN11", "x6", "b", "x7"), n("MN12", "x7", "ci", "vss"),
        pm("MP6", "x8", "a", "vdd"), pm("MP7", "x8", "b", "vdd"), pm("MP8", "x8", "ci", "vdd"),
        pm("MP9", "sn", "cn", "x8"),
        pm("MP10", "sn", "a", "x9"), pm("MP11", "x9", "b", "x10"), pm("MP12", "x10", "ci", "vdd"),
        "    // output inverters",
        pm("MP13", "co", "cn", "vdd"), n("MN13", "co", "cn", "vss"),
        pm("MP14", "s", "sn", "vdd"), n("MN14", "s", "sn", "vss")],
        "28T mirror full adder")
    return "\n".join(out)


def alu_text(circuit):
    pins = INPUTS + OUTPUTS + list(UNIT_SUPPLY.values()) + ["vss"]
    out = ["// 8-bit low-power ALU, transistor level  (generated by gen_netlist.py from model/alu_gates.py)",
           "// Separate supply pins per block let you measure each block's power.",
           "simulator lang=spectre", "",
           "subckt alu8 (" + " ".join(pins) + ")"]
    unit_now = None
    for k, g in enumerate(circuit.gates):
        if g["unit"] != unit_now:
            unit_now = g["unit"]
            out.append(f"    // ---------------- {unit_now} ----------------")
        sup = UNIT_SUPPLY[g["unit"]]
        nodes = [("vss" if x == GND else sup if x == VDD else x) for x in g["ins"] + g["outs"]]
        out.append(f"    I{k}_{g['outs'][0]} ({' '.join(nodes)} {sup} vss) {CELL_NAME[g['t']]}")
    out.append("ends alu8")
    return "\n".join(out) + "\n"


def read_vectors():
    with open(os.path.join(ROOT, "model", "test_vectors.csv")) as f:
        return list(csv.DictReader(f))


def pwl(bits, T, tr):
    """bits: list of 0/1 per vector -> Spectre pwl wave (0..1 V; scaled by a vcvs to vdd)"""
    pts = [(0.0, bits[0])]
    for k in range(1, len(bits)):
        if bits[k] != bits[k-1]:
            pts += [(k*T, bits[k-1]), (k*T + tr, bits[k])]
    pts.append((len(bits)*T, bits[-1]))
    fmt = lambda t: ("%.3f" % t).rstrip("0").rstrip(".")
    return " ".join(f"{fmt(t)}n {v}" for t, v in pts)


def tb_text(p, vecs, isooff, model_file, section):
    T, tr = T_PERIOD_NS, T_RISE_PS / 1000.0
    nvec = len(vecs)
    bits = {}
    for i in range(8):
        bits[f"A{i}"] = [(int(v["A_hex"], 16) >> i) & 1 for v in vecs]
        bits[f"B{i}"] = [(int(v["B_hex"], 16) >> i) & 1 for v in vecs]
    for i in range(4):
        bits[f"OP{i}"] = [(int(v["op_bin"], 2) >> i) & 1 for v in vecs]
    o = [f"// Transient testbench for alu8 - operand isolation {'OFF' if isooff else 'ON'}",
         "// generated by gen_netlist.py ; vectors = model/test_vectors.csv",
         f"// {nvec} vectors x {T:g} ns.  Run:  spectre tb_alu8{'_noiso' if isooff else ''}.scs "
         f"+aps -format psfxl -raw ./psf{'_noiso' if isooff else ''}",
         "simulator lang=spectre", "global 0", "",
         f'include "{model_file}" section={section}',
         'include "cells.scs"', 'include "alu8.scs"', "",
         f"parameters vdd={p['vdd']} isooff={isooff} cl=5f", "",
         "// ---- supplies (one per block -> per-block power)"]
    for unit, net in UNIT_SUPPLY.items():
        o.append(f"V{unit} ({net} 0) vsource dc=vdd type=dc")
    o += ["VISO (ISO_OFF 0) vsource dc=isooff*vdd type=dc", "",
          "// ---- input stimulus: 0/1 V PWL, scaled to vdd by a VCVS (so vdd can be swept)"]
    for name in INPUTS[:-1]:
        o.append(f"V{name}_raw ({name}_raw 0) vsource type=pwl wave=[ {pwl(bits[name], T, tr)} ]")
        o.append(f"E{name} ({name} 0 {name}_raw 0) vcvs gain=vdd")
    o += ["", "// ---- device under test",
          "XALU (" + " ".join(INPUTS + OUTPUTS + list(UNIT_SUPPLY.values()) + ["0"]) + ") alu8", "",
          "// ---- output loads"]
    for name in OUTPUTS:
        o.append(f"CL_{name} ({name} 0) capacitor c=cl")
    o += ["", "// ---- analysis",
          "simulatorOptions options temp=27 tnom=27 reltol=1e-3 vabstol=1e-6 iabstol=1e-12",
          f"tran1 tran stop={nvec*T:g}n errpreset=moderate",
          "save " + " ".join(INPUTS + OUTPUTS),
          "save " + " ".join(f"V{u}:p" for u in UNIT_SUPPLY), ""]
    return "\n".join(o)


def ocean_text(p, vecs):
    rows = []
    for v in vecs:
        rows.append(f'  list({v["idx"]} "{v["op"]}" {int(v["A_hex"],16)} {int(v["B_hex"],16)} '
                    f'{int(v["Y_hex"],16)} {int(v["YH_hex"],16)} {v["C"]} {v["Z"]} {v["N"]} {v["V"]} {v["WE"]})')
    return f""";; OCEAN check script for the 8-bit ALU (generated by gen_netlist.py)
;; Usage (from this folder, after running spectre):
;;   ocean
;;   > resDir = "./psf"        ; or "./psf_noiso"
;;   > load("alu8_check.ocn")
;; It samples every output near the end of each {T_PERIOD_NS:g} ns slot, compares with the
;; golden model, then prints average power per block and the worst-case ADD delay.

unless( boundp('resDir) resDir = "./psf" )
vdd = {p['vdd']}
T   = {T_PERIOD_NS:g}e-9
openResults(resDir)
selectResult('tran)

procedure( aluBit(sig t)
  if( value(getData(sig ?result 'tran) t) > vdd/2.0 then 1 else 0)
)
procedure( aluByte(prefix t)
  let( ((acc 0))
    for( i 0 7  acc = acc + leftshift(aluBit(sprintf(nil "%s%d" prefix i) t) i) )
    acc)
)

expected = list(
{chr(10).join(rows)}
)

errors = 0
printf("\\n idx op    A    B  |  Y  (exp)  YH (exp) | C Z N V WE | result\\n")
foreach( vec expected
  k  = nth(0 vec)
  t  = (k + 1) * T - 1e-9
  y  = aluByte("Y" t)
  yh = aluByte("YH" t)
  fl = list(aluBit("C" t) aluBit("Z" t) aluBit("N" t) aluBit("V" t) aluBit("WE" t))
  ok = (y == nth(4 vec)) && (yh == nth(5 vec)) && (fl == list(nth(6 vec) nth(7 vec) nth(8 vec) nth(9 vec) nth(10 vec)))
  unless( ok errors = errors + 1 )
  printf("%3d %-4s %4d %4d | %3d (%3d) %3d (%3d) | %d %d %d %d %d  | %s\\n"
    k nth(1 vec) nth(2 vec) nth(3 vec) y nth(4 vec) yh nth(5 vec)
    nth(0 fl) nth(1 fl) nth(2 fl) nth(3 fl) nth(4 fl) if(ok "PASS" "FAIL"))
)
printf("\\nFunctional check: %d / %d vectors failed\\n" errors length(expected))

;; ---- average power per block (P = -avg(I) * VDD; supply current flows out of the + pin)
total = 0.0
foreach( blk list("ctrl" "arith" "mul" "logic" "shift")
  pw = -average(getData(sprintf(nil "V%s:p" blk) ?result 'tran)) * vdd
  total = total + pw
  printf("  P(%-5s) = %8.3f uW\\n" blk pw*1e6)
)
printf("  P(total) = %8.3f uW   energy/op = %.3f pJ\\n" total*1e6 total*T*1e12)

;; ---- worst-case carry ripple: vector 1 is ADD FF+01 -> Z rises after the carry ripples 8 stages
tz = cross(clip(getData("Z" ?result 'tran) T 2*T) vdd/2.0 1 'rising)
printf("  ADD FF+01 carry-ripple delay (input edge -> Z) = %.1f ps\\n" (tz - T)*1e12)
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pdk", choices=PDKS, default="gpdk045")
    ap.add_argument("--nmos"); ap.add_argument("--pmos")
    ap.add_argument("--model-file"); ap.add_argument("--section")
    ap.add_argument("--vdd", type=float)
    a = ap.parse_args()
    p = dict(PDKS[a.pdk])
    for k in ("nmos", "pmos", "vdd"):
        if getattr(a, k) is not None:
            p[k] = getattr(a, k)
    model_file = a.model_file or p["model_file"]
    section = a.section or p["section"]

    c = build()
    vecs = read_vectors()
    files = {
        "cells.scs": cells_text(p),
        "alu8.scs": alu_text(c),
        "tb_alu8.scs": tb_text(p, vecs, 0, model_file, section),
        "tb_alu8_noiso.scs": tb_text(p, vecs, 1, model_file, section),
        "alu8_check.ocn": ocean_text(p, vecs),
    }
    for name, text in files.items():
        with open(os.path.join(HERE, name), "w", newline="\n") as f:
            f.write(text)

    # transistor count report
    tcount = {"INV": 2, "BUF": 4, "NAND2": 4, "NOR2": 4, "AND2": 6, "OR2": 6, "XOR2": 12,
              "XNOR2": 12, "MUX2": 6, "MUX4": 22, "FA": 28}
    by_unit = {}
    for g in c.gates:
        by_unit[g["unit"]] = by_unit.get(g["unit"], 0) + tcount[g["t"]]
    print(f"PDK preset {a.pdk}: nmos={p['nmos']} pmos={p['pmos']} L={p['l']} VDD={p['vdd']} V")
    print(f"cells: {len(c.gates)}   transistors: {sum(by_unit.values())}  " +
          "  ".join(f"{u}={n}" for u, n in by_unit.items()))
    print(f"testbench: {len(vecs)} vectors x {T_PERIOD_NS:g} ns = {len(vecs)*T_PERIOD_NS:g} ns transient")
    print("wrote: " + ", ".join(files))
    if "/path/to" in model_file:
        print("NOTE: edit the include line in tb_alu8*.scs (or pass --model-file) to point at your PDK models.")


if __name__ == "__main__":
    main()
